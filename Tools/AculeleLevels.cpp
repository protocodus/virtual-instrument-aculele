// Aculele's levels on Reason's channel meter (Tools/ReasonMeter.h).
//
//   AculeleLevels --write Source/DSP/LevelMatchData.h [--jobs N]
//   AculeleLevels --report [--jobs N]
//   AculeleLevels --check [--jobs N]
//
// --write measures typical playing in every cell, each shape, wood and
// Picking, on each Capture (the stereo pair, the mono microphone and the
// piezo), at Concert Strum's other controls with nylon strings in Standard
// tuning and no Piezo Mix, and writes the factor that brings each reading to
// targetVu at 0 dB Output. It reads at -20 dB Output, below the safety
// limiter, and adds the 20 dB back; the factors already compiled in are
// divided out, so a rerun after an engine change re-pins them.
//
// --report reads each factory preset as Reason hears it, through the output
// stage: as it is, on the other Captures, with Piezo Mix and with each
// Picking, and its loudest chords on its own Picking and on Pick. It prints
// the Output trim that brings its typical playing to targetVu.
//
// --check, the audio-tier test Aculele.Levels, reports and fails unless every
// preset reads targetVu within half a decibel; every Capture and Picking reads
// within 1.5 dB of it, so switching one is no jump; Piezo Mix moves the
// level by at most 3 dB; and the loudest chords, on the preset's Picking and
// on Pick, stay under -1 VU, out of the red, with every sample under the
// output stage's -1.5 dBFS ceiling. When an engine change moves a reading,
// rerun --write and the preset trims rather than move these bounds.

#include "DSP/AculelePresets.h"
#include "DSP/OutputStage.h"
#include "DSP/LevelMatchData.h"
#include "ReasonMeter.h"

#include <atomic>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <functional>
#include <string>
#include <thread>
#include <vector>

namespace
{
using namespace aculele;

constexpr double targetVu = -9.0;
constexpr double readingOffsetDb = 20.0;
constexpr CaptureType captures[] { CaptureType::StereoMic, CaptureType::MonoMic, CaptureType::Piezo };
const char* const captureNames[] { "stereo", "mono", "piezo" };

void parallel(std::size_t count, int jobs, const std::function<void(std::size_t)>& work)
{
    std::atomic<std::size_t> next { 0 };
    std::vector<std::thread> threads;
    for (int j = 0; j < jobs; ++j)
        threads.emplace_back([&] {
            for (std::size_t i = next++; i < count; i = next++)
                work(i);
        });
    for (auto& thread : threads)
        thread.join();
}

// A preset's parameters with Output lowered by readingOffsetDb.
EngineParameters belowLimiter(EngineParameters parameters)
{
    parameters.outputGain *= static_cast<float>(std::pow(10.0, -readingOffsetDb / 20.0));
    return parameters;
}

double typical(const EngineParameters& parameters)
{
    return meter::typicalReading(belowLimiter(parameters)) + readingOffsetDb;
}


void writeTable(std::ofstream& out, const char* name, const std::vector<double>& factors)
{
    out << "inline constexpr std::array<float, 36> " << name << " {{\n";
    for (std::size_t i = 0; i < factors.size(); ++i)
    {
        char value[32];
        std::snprintf(value, sizeof value, "%.6gf", factors[i]);
        out << (i % 6 == 0 ? "    " : " ") << value << (i + 1 < factors.size() ? "," : "")
            << (i % 6 == 5 || i + 1 == factors.size() ? "\n" : "");
    }
    out << "}};\n";
}

int write(const char* path, int jobs)
{
    const std::array<const std::array<float, 36>*, 3> compiled {
        &detail::stereoMicLevel, &detail::monoMicLevel, &detail::piezoLevel };
    std::vector<double> factors(3 * 36), readings(3 * 36);
    parallel(factors.size(), jobs, [&](std::size_t job) {
        const std::size_t capture = job / 36, cell = job % 36;
        auto parameters = engineParameters(factoryPresets[0]);
        parameters.shape = static_cast<BodyShape>(cell / 12);
        parameters.bodyMaterial = static_cast<BodyMaterial>(cell / 4 % 3);
        parameters.picking = static_cast<PickingTechnique>(cell % 4);
        parameters.capture = captures[capture];
        parameters.strings = StringMaterial::Nylon;
        parameters.tuning = Tuning::Standard;
        parameters.piezoMix = 0.0f;
        parameters.outputGain = 1.0f;
        readings[job] = typical(parameters);
        factors[job] = (*compiled[capture])[cell] * std::pow(10.0, (targetVu - readings[job]) / 20.0);
    });
    for (std::size_t capture = 0; capture < 3; ++capture)
    {
        std::printf("%-6s", captureNames[capture]);
        for (std::size_t cell = 0; cell < 36; ++cell)
            std::printf(" %6.2f", readings[capture * 36 + cell]);
        std::printf("\n");
    }
    std::ofstream out(path);
    out << "// Generated by Tools/AculeleLevels.cpp; do not edit by hand.\n#pragma once\n\n"
           "#include <array>\n\nnamespace aculele::detail\n{\n"
           "// Each factor brings typical playing (Tools/ReasonMeter.h) on its Capture to\n";
    char line[160];
    std::snprintf(line, sizeof line, "// %.0f VU on Reason's channel meter at 0 dB Output. A cell is\n", targetVu);
    out << line << "//   (shape * 3 + wood) * 4 + picking\n// in the enums' order in AculeleEngine.h.\n";
    for (std::size_t capture = 0; capture < 3; ++capture)
        writeTable(out, capture == 0 ? "stereoMicLevel" : capture == 1 ? "monoMicLevel" : "piezoLevel",
                   std::vector<double>(factors.begin() + static_cast<long>(capture * 36),
                                       factors.begin() + static_cast<long>(capture * 36 + 36)));
    out << "} // namespace aculele::detail\n";
    return out ? 0 : 1;
}

int report(int jobs, bool check)
{
    struct Row
    {
        double own, capture[3], piezoMix[2], picking[4], loudestOwnVu, loudestOwnPeak, loudestPickVu,
            loudestPickPeak;
    };
    std::vector<Row> rows(factoryPresets.size());
    // 13 readings a preset, one job each.
    parallel(rows.size() * 13, jobs, [&](std::size_t job) {
        const auto& preset = factoryPresets[job / 13];
        auto& row = rows[job / 13];
        auto parameters = engineParameters(preset);
        const std::size_t task = job % 13;
        if (task == 0)
            row.own = meter::typicalReading(parameters);
        else if (task <= 3)
        {
            parameters.capture = captures[task - 1];
            row.capture[task - 1] = meter::typicalReading(parameters);
        }
        else if (task <= 5)
        {
            if (parameters.capture == CaptureType::Piezo)
                parameters.capture = CaptureType::StereoMic;
            parameters.piezoMix = task == 4 ? 0.5f : 1.0f;
            row.piezoMix[task - 4] = meter::typicalReading(parameters);
        }
        else if (task <= 9)
        {
            parameters.picking = static_cast<PickingTechnique>(task - 6);
            row.picking[task - 6] = meter::typicalReading(parameters);
        }
        else if (task == 10 || task == 11)
        {
            if (task == 11)
                parameters.picking = PickingTechnique::Pick;
            const auto render = meter::render(parameters, meter::loudestChords());
            const double vu = *std::max_element(render.eventReadings.begin(), render.eventReadings.end());
            (task == 10 ? row.loudestOwnVu : row.loudestPickVu) = vu;
            (task == 10 ? row.loudestOwnPeak : row.loudestPickPeak) = render.peakDbfs;
        }
    });
    std::printf("%-31s %6s %6s | %6s %6s %6s | mix.5  mix1 | finger  pick thumb strum | loud own  peak | "
                "loud pick  peak\n", "preset", "Output", "VU", "stereo", "mono", "piezo");
    for (std::size_t i = 0; i < rows.size(); ++i)
    {
        const auto& r = rows[i];
        std::printf("%-31s %+6.1f %6.2f | %6.2f %6.2f %6.2f | %5.2f %5.2f | %6.2f %5.2f %5.2f %5.2f | "
                    "%8.2f %5.2f | %9.2f %5.2f   trim %+5.1f\n",
                    factoryPresets[i].name, static_cast<double>(factoryPresets[i].outputDecibels), r.own,
                    r.capture[0], r.capture[1], r.capture[2], r.piezoMix[0], r.piezoMix[1], r.picking[0],
                    r.picking[1], r.picking[2], r.picking[3], r.loudestOwnVu, r.loudestOwnPeak,
                    r.loudestPickVu, r.loudestPickPeak,
                    static_cast<double>(factoryPresets[i].outputDecibels) + targetVu - r.own);
    }
    if (!check)
        return 0;

    int failures = 0;
    const auto expect = [&failures](bool ok, const char* preset, const char* what, double value) {
        if (!ok)
        {
            std::printf("FAIL %s: %s (%.2f)\n", preset, what, value);
            ++failures;
        }
    };
    const double ceilingDbfs = 20.0 * std::log10(static_cast<double>(protocodus::OutputStage<2>::kCeiling));
    for (std::size_t i = 0; i < rows.size(); ++i)
    {
        const auto& r = rows[i];
        const char* name = factoryPresets[i].name;
        expect(std::abs(r.own - targetVu) <= 0.5, name, "typical playing is not at the target", r.own);
        for (const double reading : r.capture)
            expect(std::abs(reading - targetVu) <= 1.5, name, "a Capture is not at the target", reading);
        for (const double reading : r.picking)
            expect(std::abs(reading - targetVu) <= 1.5, name, "a Picking is not at the target", reading);
        for (const double reading : r.piezoMix)
            expect(std::abs(reading - r.own) <= 3.0, name, "Piezo Mix jumps the level", reading - r.own);
        for (const double reading : { r.loudestOwnVu, r.loudestPickVu })
            expect(reading < -1.0, name, "the loudest chords reach the red", reading);
        for (const double peak : { r.loudestOwnPeak, r.loudestPickPeak })
            expect(peak <= ceilingDbfs + 0.01, name, "a sample passes the ceiling", peak);
    }
    if (failures == 0)
        std::printf("levels pass\n");
    return failures == 0 ? 0 : 1;
}
} // namespace

int main(int argc, char** argv)
{
    int jobs = 4;
    for (int i = 1; i + 1 < argc; ++i)
        if (!std::strcmp(argv[i], "--jobs"))
            jobs = std::max(1, std::atoi(argv[i + 1]));
    if (argc >= 3 && !std::strcmp(argv[1], "--write"))
        return write(argv[2], jobs);
    if (argc >= 2 && (!std::strcmp(argv[1], "--report") || !std::strcmp(argv[1], "--check")))
        return report(jobs, !std::strcmp(argv[1], "--check"));
    std::fprintf(stderr, "usage: AculeleLevels --write <LevelMatchData.h> | --report | --check [--jobs N]\n");
    return 2;
}
